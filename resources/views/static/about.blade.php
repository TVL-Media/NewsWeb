    <h2>What NextGenNews is</h2>
    <p>NextGenNews is a short-news service for India. Every story is a card of about 60 words, so you can catch up on the day in a few minutes. You can read in Hindi or English, and switch any time.</p>
    <p>Each card gives you more than one way to read:</p>
    <ul>
        <li><strong>Key Points</strong> – the main facts in a few lines.</li>
        <li><strong>Explain Simply</strong> – the same story in plain, everyday language.</li>
        <li><strong>Full Story</strong> – a link to the original report from the source publisher.</li>
    </ul>
    <p>You can also listen to <strong>Morning 5</strong>, a short audio briefing of five stories to start your day. The audio is generated with text-to-speech. There is a daily quiz, polls on the news, and pages you can follow for the topics, places and subjects you care about.</p>
    <p>You can read without an account. If you log in with your mobile number and a one-time password (OTP), you can like, comment, share and save stories, follow pages, vote in polls, take the quiz and keep a reading streak.</p>

    <h2>How our stories are made</h2>
    <p>Our stories come from licensed news agency feeds and from publisher RSS feeds. We always link to the original source so you can read the full report.</p>
    <p>An AI system helps our editors write a first draft of each card in our own words. Every draft then goes through automated checks for facts, copy and sensitivity.</p>
    <ul>
        <li><strong>Low-risk stories</strong> – such as routine sports results, weather or product launches – may publish automatically once they pass these checks. Editors review them after publishing and fix anything that needs it.</li>
        <li><strong>Sensitive stories always wait for a human editor.</strong> This covers politics, elections, crime, courts, religion, health claims, deaths, disasters and anything involving children. No story on these topics goes live until an editor has read and approved it.</li>
    </ul>
    <p>AI can make mistakes, and so can people. That is why we link every card to its source, and why we take corrections seriously.</p>

    <h2>Corrections</h2>
    <p>If we get something wrong, we fix it. A corrected story carries a clear <strong>correction</strong> label explaining what changed. We do not quietly edit facts.</p>
    <p>If you spot an error, tap <strong>Report this story</strong> on the card and tell us what is wrong. Our editors review every report. For formal complaints about our content, you can contact our <a href="{{ route('grievance') }}">Grievance officer</a>.</p>

