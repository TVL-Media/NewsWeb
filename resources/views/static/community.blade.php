<x-static-page title="Community rules" description="Simple do's and don'ts for comments and user polls on NextGenNews, and how reporting and moderation work." updated="5 November 2026">
    <h2>The short version</h2>
    <p>Discuss the news, not the person. Disagree politely. Keep it legal. These rules apply to comments and to polls you create.</p>

    <h2>Do</h2>
    <ul>
        <li>Be respectful, even when you strongly disagree.</li>
        <li>Stay on topic and add something useful to the discussion.</li>
        <li>Check facts before you share them, and link to a reliable source where you can.</li>
        <li>Report posts that break these rules instead of replying in anger.</li>
    </ul>

    <h2>Don't</h2>
    <ul>
        <li><strong>No hate speech or communal content.</strong> Do not attack or insult anyone for their religion, caste, community, gender, region, language, disability or sexual orientation.</li>
        <li><strong>No harassment.</strong> No threats, bullying, abuse or targeting of other users.</li>
        <li><strong>No misinformation.</strong> Do not post content you know is false or misleading.</li>
        <li><strong>No personal data or doxxing.</strong> Do not share anyone's phone number, address, documents or other private details – including your own.</li>
        <li><strong>No spam or promotions.</strong> No ads, referral links, repeated posts or self-promotion.</li>
        <li><strong>No impersonation.</strong> Do not pretend to be another person, a public figure, an organisation or NextGenNews staff.</li>
        <li><strong>No sexual content.</strong> No obscene or sexually explicit text or links.</li>
        <li><strong>Nothing illegal.</strong> Nothing that breaks Indian law, encourages violence or harms children.</li>
    </ul>

    <h2>User polls</h2>
    <p>You can suggest polls on the news. Every user poll is reviewed by our editors before it goes live. We may edit a poll for clarity or decline it if it breaks these rules, is misleading, or targets a person or community.</p>

    <h2>Limits and filters</h2>
    <ul>
        <li>Accounts less than 24 hours old can post at most 3 comments a day. This helps keep out spam.</li>
        <li>A profanity filter checks comments automatically. Comments with abusive words may be blocked or held for review.</li>
    </ul>

    <h2>Reporting and moderation</h2>
    <p>Tap <strong>Report</strong> on any comment or poll that breaks these rules. Our moderators review reports, and serious ones are handled first. Depending on what happened, we may:</p>
    <ol>
        <li><strong>Hide</strong> the comment or poll.</li>
        <li><strong>Warn</strong> the person who posted it.</li>
        <li><strong>Suspend</strong> their ability to comment or create polls, or suspend the account – for a time or permanently – for serious or repeated breaches.</li>
    </ol>
    <p>Where the law requires, we may also report content to the authorities.</p>

    <h2>Appeals</h2>
    <p>If you think we made a wrong call, you can appeal to our <a href="{{ route('grievance') }}">Grievance officer</a>. Include a link to the content and explain why you think the decision should change.</p>

