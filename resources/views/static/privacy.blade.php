    <h2>Summary</h2>
    <p>NextGenNews collects only the data we need to run the service. We do not sell your personal data. You can read the news without an account. If you create one, you can see, correct or delete your data at any time.</p>
    <p>This policy explains how we handle your personal data under the Digital Personal Data Protection Act, 2023 (DPDP Act), the Information Technology Act, 2000 and related rules. In this policy, "we" and "us" mean NextGenNews, which acts as the Data Fiduciary for your data.</p>

    <h2>Data we collect</h2>
    <h3>When you create an account</h3>
    <ul>
        <li><strong>Mobile number</strong> – to log you in with a one-time password (OTP).</li>
        <li><strong>OTP records</strong> – we store only a hashed (scrambled) form of each OTP, briefly, to check it. We never store the OTP itself in readable form.</li>
        <li><strong>Profile details</strong> – your name, preferred language and city, if you give them.</li>
    </ul>
    <h3>When you use the service</h3>
    <ul>
        <li>Topics you choose and pages you follow.</li>
        <li>Your likes, comments, saves, shares, reactions and poll votes.</li>
        <li>Your reading history, so we can count your reading streak.</li>
        <li>Your daily quiz attempts and scores.</li>
    </ul>
    <h3>Collected automatically</h3>
    <ul>
        <li><strong>Device and log data</strong> – such as IP address, browser and device type, operating system, pages viewed and the time of each request.</li>
        <li><strong>Cookies</strong> – a session cookie that keeps you logged in and protects forms, and a language cookie that remembers whether you read in Hindi or English. These are needed for the site to work.</li>
        <li><strong>Analytics</strong> – we use Google Analytics 4 to understand how people use NextGenNews, such as which sections are popular. It uses its own cookies and identifiers.</li>
        <li><strong>Error data</strong> – we use Sentry to find and fix crashes. When something breaks, it may record technical details such as the page, browser, device and the error itself.</li>
    </ul>

    <h2>Why we use your data</h2>
    <ul>
        <li>To create your account and log you in securely.</li>
        <li>To show news in your language and on topics, places and pages you follow.</li>
        <li>To let you like, comment, save, share, vote and take the quiz, and to keep your streak.</li>
        <li>To moderate comments and polls, and to prevent spam, fraud and abuse.</li>
        <li>To measure and improve the service and fix errors.</li>
        <li>To respond to your complaints and requests.</li>
        <li>To meet our legal obligations, including lawful requests from government authorities.</li>
    </ul>
    <p>We do not use your personal data to make decisions that have legal or similarly significant effects on you.</p>

    <h2>Legal basis and consent</h2>
    <p>We process your personal data based on your consent, which you give when you create an account and agree to this policy, or for legitimate uses allowed under the DPDP Act, such as complying with law or a court order. We ask for consent in clear language and only for the purposes listed above.</p>
    <p>You can withdraw your consent at any time by deleting your account or writing to our Grievance Officer. Withdrawing consent does not affect processing already done. Some features will stop working without the data they need.</p>

    <h2>Who we share data with</h2>
    <p>We share personal data only with service providers who help us run NextGenNews, and only what they need to do their job:</p>
    <ul>
        <li><strong>SMS provider</strong> – to send your OTP to your mobile number.</li>
        <li><strong>Cloud hosting and storage providers</strong> – to run our servers and store data.</li>
        <li><strong>Analytics provider</strong> (Google Analytics 4) – to measure usage.</li>
        <li><strong>Error tracking provider</strong> (Sentry) – to find and fix technical problems.</li>
    </ul>
    <p>These providers act as Data Processors under contract with us. Some of them may process data outside India, in countries not restricted by the Government of India under the DPDP Act.</p>
    <p>We may also disclose data when required by law, a court order or a lawful request from a government agency. Your public comments, display name and poll entries are visible to other users.</p>
    <p><strong>We do not sell your personal data.</strong></p>

    <h2>How long we keep data</h2>
    <ul>
        <li>OTP hashes are deleted shortly after they expire.</li>
        <li>Account data is kept while your account is active. When you delete your account, we delete or anonymise your personal data, except where the law requires us to keep it longer.</li>
        <li>Log and error data are kept only as long as needed for security and fixing problems, and then deleted.</li>
        <li>Where the IT Rules, 2021 require it, we keep certain records for a limited period (for example, 180 days) for investigation purposes.</li>
    </ul>

    <h2>Your rights</h2>
    <p>Under the DPDP Act, you have the right to:</p>
    <ul>
        <li><strong>Access</strong> – get a summary of the personal data we hold about you and how we use it.</li>
        <li><strong>Correction</strong> – correct, complete or update inaccurate data. You can edit most profile details yourself.</li>
        <li><strong>Erasure</strong> – ask us to delete your personal data.</li>
        <li><strong>Grievance redressal</strong> – complain to our Grievance Officer, and if not satisfied, to the Data Protection Board of India.</li>
        <li><strong>Nominate</strong> – name another person to exercise your rights if you die or become unable to do so.</li>
    </ul>
    <p>To use any of these rights, write to our <a href="{{ route('grievance') }}">Grievance Officer</a>. We may need to confirm your identity first.</p>

    <h2>Deleting your account</h2>
    <p>You can delete your account from your profile settings, or by asking our Grievance Officer. Once deleted, your profile, follows, saves, streaks and quiz history are removed. Your comments are removed or anonymised.</p>

    <h2>Children</h2>
    <p>NextGenNews is not directed at children under 18. Under the DPDP Act, we do not knowingly create accounts for anyone under 18 without verifiable consent from a parent or lawful guardian. We do not track or target advertising at children. If you believe a child has created an account without such consent, please contact us and we will delete it.</p>

    <h2>Security</h2>
    <p>We use reasonable security safeguards to protect your data, including encrypted connections (HTTPS), hashed OTPs, access controls and limited staff access. No system is perfectly secure. If a personal data breach happens, we will inform affected users and the Data Protection Board of India as the law requires.</p>

    <h2>Changes to this policy</h2>
    <p>We may update this policy from time to time. We will change the "Last updated" date above and, for significant changes, tell you in the app before they take effect.</p>

    <h2>Contact</h2>
    <p>For questions or requests about your data, contact our <a href="{{ route('grievance') }}">Grievance Officer</a>. See also our <a href="{{ route('terms') }}">Terms of use</a>.</p>
